import { mkdir, rm } from 'node:fs/promises';
import { spawn } from 'node:child_process';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const artifact = path.resolve(process.env.VERIROUTER_ARTIFACT_DIR || path.join(root, '../VeriRouter-release'));
const destination = path.join(root, 'server/artifact');
if (artifact === destination) throw new Error('Use the source checkout as VERIROUTER_ARTIFACT_DIR.');
await rm(destination, { recursive: true, force: true });
await mkdir(destination, { recursive: true });
await new Promise((resolve, reject) => {
  const archive = spawn('git', ['-C', artifact, 'archive', 'HEAD'], { stdio: ['ignore', 'pipe', 'inherit'] });
  const unpack = spawn('tar', ['-x', '-C', destination], { stdio: ['pipe', 'ignore', 'inherit'] });
  archive.stdout.pipe(unpack.stdin);
  archive.on('error', reject); unpack.on('error', reject);
  let archiveCode, unpackCode;
  const finish = () => { if (archiveCode === undefined || unpackCode === undefined) return;
    if (archiveCode || unpackCode) reject(new Error('Could not prepare the release artifact.')); else resolve(); };
  archive.on('close', (code) => { archiveCode = code; finish(); });
  unpack.on('close', (code) => { unpackCode = code; finish(); });
});
console.log('Prepared ignored server/artifact/ for the container build.');
